import { describe, it, expect, beforeEach } from "vitest";
import { LocalStoragePlanRepository } from "../src/repository/localStorageRepo";
import { EventPlan } from "../src/repository/types";

const mockPlan: EventPlan = {
  id: "plan-test-1",
  name: "Meera & Rohan Wedding",
  event_type: "wedding",
  event_date: "2026-12-15",
  location: "Udaipur, Rajasthan",
  guest_count: 200,
  total_budget: 2000000,
  style: "Royal Heritage",
  theme: "Marigold Yellow",
  special_requirements: "Pure Vegetarian Jain counters",
  source: "gemini",
  source_explanation: "Generated by Gemini 2.5 Flash",
  budget: {
    total_budget: 2000000,
    total_planned: 1900000,
    total_actual: 0,
    total_effective: 1900000,
    remaining_budget: 100000,
    is_over_budget: false,
    over_budget_amount: 0,
    categories: [],
    items: [],
  },
  timeline: {
    event_date: "2026-12-15",
    current_ist_date: "2026-10-26",
    days_remaining: 50,
    is_past_event: false,
    has_overdue_milestones: false,
    has_at_risk_milestones: false,
    alert_banner: null,
    milestones: [],
  },
  vendors: [],
  ideas: {
    decor: [],
    food: [],
    activities: [],
    themes: [],
    logistics: [],
  },
  created_at: "2026-10-26",
  updated_at: "2026-10-26",
};

describe("LocalStoragePlanRepository Resilience & Recovery", () => {
  let repo: LocalStoragePlanRepository;

  beforeEach(() => {
    localStorage.clear();
    repo = new LocalStoragePlanRepository();
  });

  it("successfully persists and retrieves a valid event plan", () => {
    repo.saveCurrentPlan(mockPlan);
    const loaded = repo.loadCurrentPlan();

    expect(loaded).not.toBeNull();
    expect(loaded?.id).toBe("plan-test-1");
    expect(loaded?.name).toBe("Meera & Rohan Wedding");
    expect(loaded?.source).toBe("gemini");
    expect(repo.getRecoveryError()).toBeNull();
  });

  it("recovers gracefully from malformed JSON without crashing", () => {
    // Inject corrupt non-JSON string into localStorage
    localStorage.setItem("eventpilot_active_plan_v1", "{corrupted_data: missing_quotes");

    const loaded = repo.loadCurrentPlan();

    expect(loaded).toBeNull();
    expect(repo.getRecoveryError()).toContain("malformed");
    // Verify corrupt data was cleaned up
    expect(localStorage.getItem("eventpilot_active_plan_v1")).toBeNull();
  });

  it("recovers gracefully from schema mismatch / missing fields without crashing", () => {
    // Inject JSON with missing required fields (e.g. missing budget and event_type)
    localStorage.setItem(
      "eventpilot_active_plan_v1",
      JSON.stringify({ name: "Partial Plan", id: "123" })
    );

    const loaded = repo.loadCurrentPlan();

    expect(loaded).toBeNull();
    expect(repo.getRecoveryError()).toContain("safely recovered");
    // Verify corrupted data was cleaned up
    expect(localStorage.getItem("eventpilot_active_plan_v1")).toBeNull();
  });

  it("clears saved plan properly", () => {
    repo.saveCurrentPlan(mockPlan);
    expect(repo.loadCurrentPlan()).not.toBeNull();

    repo.clearPlan();
    expect(repo.loadCurrentPlan()).toBeNull();
  });
});
